"""Task 4.3: threaded logger with file rotation."""

from __future__ import annotations

import threading
from pathlib import Path
from queue import Empty, Queue
from time import perf_counter
from typing import TextIO


class ThreadedLogger:
    """Threaded logger with file rotation and graceful shutdown.

    Args:
        log_path: path to the log file
        max_lines: maximum number of lines per file before rotation
        n_producers: number of producer threads
        messages_per_producer: number of messages generated by each producer
    """

    def __init__(
        self,
        log_path: Path | str,
        max_lines: int = 100,
        n_producers: int = 3,
        messages_per_producer: int = 10,
    ) -> None:
        if max_lines <= 0:
            raise ValueError("max_lines must be > 0")
        if n_producers <= 0:
            raise ValueError("n_producers must be > 0")
        if messages_per_producer < 0:
            raise ValueError("messages_per_producer must be >= 0")

        self.log_path = Path(log_path)
        self.max_lines = max_lines
        self.n_producers = n_producers
        self.messages_per_producer = messages_per_producer

        self._queue: Queue[str] = Queue()
        self._write_lock = threading.RLock()
        self._stop_event = threading.Event()
        self._producers_done_event = threading.Event()

        self._state_lock = threading.Lock()
        self._producer_threads: list[threading.Thread] = []
        self._consumer_thread: threading.Thread | None = None
        self._started = False

        self._finished_producers = 0
        self._rotation_index = 0
        self._lines_in_current_file = 0
        self._writer: TextIO | None = None

    def start(self) -> None:
        """Start producer threads and a consumer thread."""
        with self._state_lock:
            if self._started:
                return
            self._started = True
            self._stop_event.clear()
            self._producers_done_event.clear()
            self._finished_producers = 0
            self._rotation_index = 0
            self._lines_in_current_file = 0
            self._producer_threads = []
            self._consumer_thread = None

        self._drain_queue()

        consumer = threading.Thread(target=self._consumer, name="logger-consumer")
        self._consumer_thread = consumer
        consumer.start()

        for producer_id in range(self.n_producers):
            producer = threading.Thread(
                target=self._producer,
                args=(producer_id,),
                name=f"logger-producer-{producer_id}",
            )
            self._producer_threads.append(producer)
            producer.start()

    def stop(self, timeout: float = 5.0) -> None:
        """Stop all threads gracefully.

        Args:
            timeout: maximum wait time for full shutdown
        """
        with self._state_lock:
            if not self._started:
                return
            producer_threads = list(self._producer_threads)
            consumer_thread = self._consumer_thread
            self._started = False

        deadline = perf_counter() + timeout

        for thread in producer_threads:
            remaining = max(0.0, deadline - perf_counter())
            thread.join(timeout=remaining)

        self._stop_event.set()
        remaining = max(0.0, deadline - perf_counter())
        if consumer_thread is not None:
            consumer_thread.join(timeout=remaining)

    def _producer(self, producer_id: int) -> None:
        """Produce messages with unique IDs."""
        for message_number in range(self.messages_per_producer):
            message_id = f"{producer_id}-{message_number}"
            message = f"[{producer_id}] {message_id}: log message {message_number}"
            self._queue.put(message)

        with self._state_lock:
            self._finished_producers += 1
            if self._finished_producers >= self.n_producers:
                self._producers_done_event.set()

    def _consumer(self) -> None:
        """Consume messages from queue and write them with rotation."""
        self._open_writer()
        try:
            while True:
                if (
                    self._stop_event.is_set()
                    and self._producers_done_event.is_set()
                    and self._queue.empty()
                ):
                    break

                try:
                    message = self._queue.get(timeout=0.05)
                except Empty:
                    continue

                self._write_message(message)
        finally:
            self._close_writer()

    def _rotate(self) -> None:
        """Rotate current file and create a new one."""
        self._close_writer()
        self._rotation_index += 1

        rotated_path = self.log_path.with_name(f"{self.log_path.name}.{self._rotation_index}")
        while rotated_path.exists():
            self._rotation_index += 1
            rotated_path = self.log_path.with_name(f"{self.log_path.name}.{self._rotation_index}")

        if self.log_path.exists():
            self.log_path.replace(rotated_path)

        self._open_writer()

    def _write_message(self, message: str) -> None:
        with self._write_lock:
            if self._writer is None:
                self._open_writer()
            if self._lines_in_current_file >= self.max_lines:
                self._rotate()
            assert self._writer is not None
            self._writer.write(f"{message}\n")
            self._writer.flush()
            self._lines_in_current_file += 1

    def _open_writer(self) -> None:
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self._writer = self.log_path.open("w", encoding="utf-8")
        self._lines_in_current_file = 0

    def _close_writer(self) -> None:
        if self._writer is None:
            return
        self._writer.close()
        self._writer = None

    def _drain_queue(self) -> None:
        while True:
            try:
                self._queue.get_nowait()
            except Empty:
                return
